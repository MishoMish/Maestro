#!/usr/bin/env python3
"""Turn the song text files into firmware data and WAV previews.

    python3 tools/make_songs.py            check songs, write header and WAVs
    python3 tools/make_songs.py --upload   same, then upload the firmware to the Uno

Uses only the Python standard library. Song format: see tools/songs/README.md.
"""
import argparse
import subprocess
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SONG_DIR = ROOT / "tools" / "songs"
PREVIEW_DIR = ROOT / "tools" / "preview"
FIRMWARE_DIR = ROOT / "code"
HEADER = FIRMWARE_DIR / "src" / "melodies_data.h"

NOTES = ["Do", "Re", "Mi", "Fa", "Sol", "La", "Si", "Do'"]
NOTE_HZ = [262, 294, 330, 349, 392, 440, 494, 523]  # same as the firmware

MIN_LEVELS, MAX_LEVELS = 8, 12      # DECISIONS.md Q4
MAX_LENGTH = 31                     # 5 bits in the stored byte
MIN_GAP_MS = 200                    # fastest press a beginner is asked for
MAX_TITLE = 16                      # LCD width
MAX_SHORT = 5                       # name on the Records page
SOUND_FRACTION = 0.85               # DECISIONS.md Q22
SAMPLE_RATE = 22050


class SongError(Exception):
    pass


def parse_song(text, source="song"):
    """Return a song dict, or raise SongError listing every problem found."""
    fields, notes, cuts, errors = {}, [], [], []
    for line_no, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if "=" in line:
            key, value = line.split("=", 1)
            fields[key.strip()] = value.strip()
            continue
        for token in line.split():
            if token == "|":
                if notes and (not cuts or cuts[-1] != len(notes)):
                    cuts.append(len(notes))
                continue
            name, slash, length = token.partition("/")
            if name not in NOTES:
                errors.append(f"line {line_no}: '{name}' is not one of the 8 keys")
            elif not slash or not length.isdigit() or not 1 <= int(length) <= MAX_LENGTH:
                errors.append(f"line {line_no}: '{token}' needs a length from 1 to {MAX_LENGTH}")
            else:
                notes.append((NOTES.index(name), int(length)))
    if notes and (not cuts or cuts[-1] != len(notes)):
        cuts.append(len(notes))

    title = fields.get("title", "")
    if not title or len(title) > MAX_TITLE or not title.isascii():
        errors.append(f"title must be 1-{MAX_TITLE} Latin characters, got '{title}'")
    short = fields.get("short", "")
    if not short or len(short) > MAX_SHORT or not short.isascii():
        errors.append(f"short must be 1-{MAX_SHORT} Latin characters, got '{short}'")
    tempo = fields.get("tempo", "")
    max_notes = fields.get("max_notes", "")
    if not tempo.isdigit() or int(tempo) == 0:
        errors.append("tempo= must be quarter notes per minute")
    if not max_notes.isdigit():
        errors.append("max_notes= must be a number")
    if errors:
        raise SongError(f"{source}:\n  " + "\n  ".join(errors))

    sixteenth_ms = round(15000 / int(tempo))
    if len(notes) > int(max_notes):
        errors.append(f"{len(notes)} notes, limit is {max_notes}")
    if not MIN_LEVELS <= len(cuts) <= MAX_LEVELS:
        errors.append(f"{len(cuts)} levels, must be {MIN_LEVELS}-{MAX_LEVELS}")
    shortest = min(length for _, length in notes[:-1]) * sixteenth_ms
    if shortest < MIN_GAP_MS:
        errors.append(f"shortest gap is {shortest} ms, minimum is {MIN_GAP_MS} ms")
    if errors:
        raise SongError(f"{source}:\n  " + "\n  ".join(errors))
    return {"title": title, "short": short, "sixteenth_ms": sixteenth_ms, "notes": notes, "cuts": cuts}


def load_songs(song_dir=SONG_DIR):
    songs, problems = [], []
    for path in sorted(song_dir.glob("*.txt")):
        try:
            song = parse_song(path.read_text(encoding="utf-8"), path.name)
            song["stem"] = path.stem
            songs.append(song)
        except SongError as err:
            problems.append(str(err))
    if problems:
        raise SongError("\n".join(problems))
    if not songs:
        raise SongError(f"no songs found in {song_dir}")
    return songs


def header_text(songs):
    out = [
        "// GENERATED by tools/make_songs.py. Do not edit: change tools/songs/*.txt instead.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "// One byte per note: top 3 bits = key (0 = Do ... 7 = Do'), low 5 bits = length in sixteenths.",
        "#define SONG_NOTE(b) ((uint8_t)(b) >> 5)",
        "#define SONG_LEN(b) ((uint8_t)(b) & 0x1F)",
        "",
        "struct Song {",
        "  const char* title;      // PROGMEM",
        "  const char* shortName;  // PROGMEM",
        "  const uint8_t* notes;   // PROGMEM",
        "  const uint8_t* cuts;    // PROGMEM: note count at the end of each level",
        "  uint16_t sixteenthMs;",
        "  uint8_t noteCount;",
        "  uint8_t levelCount;",
        "};",
        "",
    ]
    for i, song in enumerate(songs):
        data = ", ".join(f"0x{(key << 5) | length:02X}" for key, length in song["notes"])
        cuts = ", ".join(str(c) for c in song["cuts"])
        out += [
            f'static const char SONG{i}_TITLE[] PROGMEM = "{song["title"]}";',
            f'static const char SONG{i}_SHORT[] PROGMEM = "{song["short"]}";',
            f"static const uint8_t SONG{i}_NOTES[] PROGMEM = {{{data}}};",
            f"static const uint8_t SONG{i}_CUTS[] PROGMEM = {{{cuts}}};",
            "",
        ]
    out += [f"#define SONG_COUNT {len(songs)}", "static const Song SONGS[SONG_COUNT] PROGMEM = {"]
    for i, song in enumerate(songs):
        out.append(
            f"  {{SONG{i}_TITLE, SONG{i}_SHORT, SONG{i}_NOTES, SONG{i}_CUTS, "
            f'{song["sixteenth_ms"]}, {len(song["notes"])}, {len(song["cuts"])}}},'
        )
    out += ["};", ""]
    return "\n".join(out)


def render_wav(song, path):
    """Square wave, like the piezo. Each note sounds for 85% of its length."""
    audio = bytearray()
    for key, length in song["notes"]:
        total = int(SAMPLE_RATE * length * song["sixteenth_ms"] / 1000)
        sounding = int(total * SOUND_FRACTION)
        half_periods = 2 * NOTE_HZ[key] / SAMPLE_RATE
        audio += bytes(188 if int(i * half_periods) % 2 == 0 else 68 for i in range(sounding))
        audio += bytes([128]) * (total - sounding)
    with wave.open(str(path), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(1)
        wav.setframerate(SAMPLE_RATE)
        wav.writeframes(bytes(audio))
    return len(audio) / SAMPLE_RATE


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--upload", action="store_true", help="also upload the firmware to the Uno")
    args = parser.parse_args()

    try:
        songs = load_songs()
    except SongError as err:
        print(f"Song errors, nothing was written:\n{err}", file=sys.stderr)
        return 1

    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(header_text(songs), encoding="utf-8")
    PREVIEW_DIR.mkdir(parents=True, exist_ok=True)
    for song in songs:
        seconds = render_wav(song, PREVIEW_DIR / f"{song['stem']}.wav")
        print(f"{song['title']:<14} {len(song['notes']):>3} notes  {len(song['cuts']):>2} levels  "
              f"{seconds:>5.1f} s  cuts {song['cuts']}")
    print(f"Wrote {HEADER.relative_to(ROOT)} and previews in {PREVIEW_DIR.relative_to(ROOT)}/")

    if args.upload:
        if not (FIRMWARE_DIR / "platformio.ini").exists():
            print("Cannot upload yet: code/platformio.ini does not exist.", file=sys.stderr)
            return 1
        return subprocess.call(["pio", "run", "-d", str(FIRMWARE_DIR), "-e", "uno", "-t", "upload"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
